"""Initial schema: runs, events, results, tools, findings, retrieval, sessions.

Sources: spec §9 tables, CR-001 §6 (sessions), CR-001 F3 (extra runs columns).

Written as explicit SQL so every constraint and index is visible in review.
Fencing is NOT enforced here yet: the `epoch` columns exist, and the trigger that
rejects stale-epoch writes arrives in phase 2 as its own migration.

LangGraph's checkpointer owns `checkpoints` / `checkpoint_writes` and creates them
itself (phase 1); they are deliberately not in our migrations.

Revision ID: 0001
Revises:
Create Date: 2026-10-11
"""

